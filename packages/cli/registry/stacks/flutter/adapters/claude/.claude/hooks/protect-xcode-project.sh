#!/usr/bin/env bash
# PreToolUse (Edit|Write|MultiEdit): deny hand edits to the iOS files Flutter and CocoaPods
# regenerate, where a text edit is lost on the next build or pod install: ios/Flutter/ephemeral/,
# ios/Flutter/Generated.xcconfig, GeneratedPluginRegistrant.*, ios/Pods/ and Podfile.lock.
# The committed Runner.xcodeproj, Info.plist, AppDelegate.swift and the Podfile stay editable;
# git shows any change to them. Fails open with a note.
set -euo pipefail
lib="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}/.claude/hooks/_lib.sh"
# agent-ops ships _lib.sh beside this hook.
# shellcheck source=/dev/null
{ [ -r "$lib" ] && source "$lib"; } 2>/dev/null || { cat >/dev/null 2>&1 || while IFS= read -r _; do :; done; echo "protect-xcode-project.sh: shared helper unavailable; allowing this call." >&2; exit 0; }
input=$(cat 2>/dev/null) || { echo "protect-xcode-project.sh: cannot read payload; allowing this call." >&2; exit 0; }
path=$(hook_get "$input" tool_input.file_path | head -n 1) || { echo "protect-xcode-project.sh: unreadable payload; allowing this call." >&2; exit 0; }
case "$path" in
*/Flutter/ephemeral/* | */Flutter/Generated.xcconfig | */GeneratedPluginRegistrant.* | */Pods/* | */Podfile.lock | Podfile.lock)
  hook_deny "$(basename "$path") is regenerated by Flutter or CocoaPods, so a hand edit is lost on the next build or pod install. Change the source instead: pubspec.yaml (flutter pub add for a plugin), the Podfile, or ios/Runner."
  ;;
esac
exit 0
