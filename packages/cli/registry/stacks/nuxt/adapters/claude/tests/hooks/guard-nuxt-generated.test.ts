import { describe, expect, it } from "vitest";
import { denyReason, REPO, runHook, write } from "../helpers/hooks";

const run = (path: string) =>
  runHook("PreToolUse", "guard-nuxt-generated", write(path, "export {};\n"));

describe.concurrent("guard-nuxt-generated denies", () => {
  it.each([
    [`${REPO}/.nuxt/tsconfig.app.json`, "is generated by Nuxt"],
    [`${REPO}/.nuxt/types/imports.d.ts`, "is generated by Nuxt"],
    [".nuxt/eslint.config.mjs", "is generated by Nuxt"],
    [`${REPO}/.output/server/index.mjs`, "is the built server"],
    [`${REPO}/.data/kv/notes.json`, "is Nitro's runtime storage"],
    [`${REPO}/test-results/notes/error-context.md`, "is Playwright output"],
    [`${REPO}/playwright-report/index.html`, "is Playwright output"],
  ])("%s", async (path, reason) => {
    expect(denyReason(await run(path))).toContain(reason);
  });
});

describe.concurrent("guard-nuxt-generated allows", () => {
  it.each([
    `${REPO}/app/pages/index.vue`,
    `${REPO}/server/api/notes.get.ts`,
    `${REPO}/nuxt.config.ts`,
    `${REPO}/tsconfig.json`,
    `${REPO}/e2e/notes.spec.ts`,
    "/somewhere/else/.nuxt/tsconfig.json",
  ])("%s", async (path) => {
    const result = await run(path);
    expect(result.code).toBe(0);
    expect(result.stdout).toBe("");
  });
});
