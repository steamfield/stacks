#!/usr/bin/env bash
# PreToolUse (Edit|Write): deny hand edits to the files CocoaPods regenerates, where a text edit is
# lost on the next `bun run pods`: ios/Pods/, Podfile.lock and the workspace's
# contents.xcworkspacedata. The committed Xcode project stays editable and git shows any change to
# it; new native code still belongs in a local module under modules/, which autolinking adds.
# Fails open when the payload is unreadable.
set -euo pipefail
lib="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}/.claude/hooks/_lib.sh"
# shellcheck source=/dev/null # agent-ops ships _lib.sh beside this hook
{ [ -r "$lib" ] && source "$lib"; } 2>/dev/null || { cat >/dev/null 2>&1 || while IFS= read -r _; do :; done; echo "protect-native-project.sh: shared helper unavailable; allowing this call." >&2; exit 0; }
input=$(cat 2>/dev/null) || { echo "protect-native-project.sh: cannot read payload; allowing this call." >&2; exit 0; }

file_path=$(hook_get "$input" tool_input.file_path | head -n 1) || exit 0
[ -n "$file_path" ] || exit 0

case "$file_path" in
*/Pods/* | Pods/* | */Podfile.lock | Podfile.lock | *.xcworkspace/contents.xcworkspacedata)
  hook_deny "$(basename "$file_path") is regenerated by CocoaPods, so a hand edit is lost on the next bun run pods. Change ios/Podfile or a module's podspec under modules/, then run bun run pods."
  ;;
esac
exit 0
