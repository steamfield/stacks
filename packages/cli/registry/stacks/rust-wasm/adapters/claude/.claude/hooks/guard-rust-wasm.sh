#!/usr/bin/env bash
# PreToolUse (Bash|Edit|Write): stop the commands that are wrong for this
# package, and edits to files a tool writes, and say what to run instead.
#
#   bun test                    Bun's runner can't load the package's .wasm import,
#                               and consumer/ tests use node:test
#   wasm-pack publish/login     publishing is the maintainer's step
#   cargo install wasm-bindgen-cli
#                               wasm-pack fetches the CLI that matches Cargo.lock;
#                               a separate install drifts from the crate
#   pkg/, target/, Cargo.lock, consumer/bun.lock, node_modules/
#                               generated by wasm-pack, cargo or bun
set -euo pipefail
command -v jq >/dev/null 2>&1 || exit 0

input="$(cat)"

deny() {
  jq -n --arg reason "$1" '{hookSpecificOutput: {
    hookEventName: "PreToolUse",
    permissionDecision: "deny",
    permissionDecisionReason: $reason
  }}'
  exit 0
}

# A command at the start of a line or after ; & | ( or $(, optionally behind
# env assignments: the words that follow are matched by each rule below.
start='(^|[;&|(]|\$\()[[:space:]]*([A-Za-z_][A-Za-z0-9_]*=[^[:space:]]*[[:space:]]+)*'

command="$(printf '%s' "$input" | jq -r '.tool_input.command // empty' 2>/dev/null)" || exit 0
if [ -n "$command" ]; then
  if printf '%s\n' "$command" | grep -Eq "${start}bun[[:space:]]+test([[:space:]]|$)"; then
    deny "bun test is Bun's own runner: it can't load this package's .wasm import, and consumer/ uses Node's test runner. Run make test-js (it packs pkg/ first), or make test and make test-wasm for the Rust side."
  fi
  if printf '%s\n' "$command" | grep -Eq "${start}wasm-pack[[:space:]]+(.*[[:space:]])?(publish|login)([[:space:]]|$)"; then
    deny "Publishing is the maintainer's step: it reaches every user and can't be taken back. Run make ci, describe the release kind (patch, minor, major) in your summary, and leave wasm-pack publish to the maintainer. make pack shows the tarball that would ship."
  fi
  if printf '%s\n' "$command" | grep -Eq "${start}cargo([[:space:]]+\+[^[:space:]]+)?[[:space:]]+(binstall|install)[[:space:]]+(.*[[:space:]])?wasm-bindgen-cli([@[:space:]]|$)"; then
    deny "wasm-pack downloads the wasm-bindgen CLI whose version matches the wasm-bindgen crate in Cargo.lock; a separately installed CLI drifts from it and the build fails on a schema mismatch. Run make build or make test-wasm."
  fi
  exit 0
fi

root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd -P)}"
physical="$(cd "$root" 2>/dev/null && pwd -P)" || physical="$root"
# Normalize dot segments and recognize both logical and physical project roots.
rel="$(printf '%s' "$input" | jq -r --arg root "$root" --arg physical "$physical" '
  def normalize:
    split("/") | reduce .[] as $part ([];
      if $part == "" or $part == "." then .
      elif $part == ".." and length > 0 and .[-1] != ".." then .[:-1]
      else . + [$part] end) | join("/");
  .tool_input.file_path | select(type == "string" and length > 0) as $path |
  ($path | normalize) as $file |
  ($root | normalize) as $logical |
  ($physical | normalize) as $real |
  if ($path | startswith("/")) then
    if ($file | startswith($logical + "/")) then $file[($logical | length) + 1:]
    elif ($file | startswith($real + "/")) then $file[($real | length) + 1:]
    else empty end
  else $file end
' 2>/dev/null)" || exit 0

case "$rel" in
  pkg/*)
    deny "pkg/ is the npm package wasm-pack generates from src/lib.rs. Change the Rust exports (or the TYPES section for TypeScript shapes) and run make build."
    ;;
  target/*)
    deny "target/ is cargo's build output, including the tarball make pack writes. Edit the source and rebuild."
    ;;
  Cargo.lock | */Cargo.lock)
    deny "Cargo.lock is written by cargo. Change dependencies with cargo add, cargo remove or cargo update -p <crate>."
    ;;
  bun.lock | */bun.lock)
    deny "bun.lock is written by bun. Change consumer/ dependencies with bun add -d or bun remove inside consumer/."
    ;;
  node_modules/* | */node_modules/*)
    deny "node_modules/ is installed by bun, and make test-js unpacks the built package there. Change the source and rerun the make target."
    ;;
esac
